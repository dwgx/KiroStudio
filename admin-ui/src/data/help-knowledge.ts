export interface HelpEntry {
  id: string
  /** i18n 键：kb.<id>.title */
  title: string
  category: Category
  tags: string[]
  /** i18n 键：kb.<id>.problem */
  problem: string
  /** i18n 键：kb.<id>.cause */
  cause: string
  /** i18n 键：kb.<id>.solution */
  solution: string
  severity: 'high' | 'medium' | 'low'
  source: string
  codePath?: string
  updatedAt: string
}

export type Category =
  | 'pitfalls'
  | 'architecture'
  | 'protocol'
  | 'deploy'
  | 'faq'
  | 'research'
  | 'config'
  | 'security'

export interface HelpModule {
  path: string
  name: string
  /** i18n 键：kb.mod.<path-slug>.role */
  role: string
  keyFiles: string[]
}

export interface HelpChainStep {
  id: string
  /** i18n 键：kb.chain.<id>.name */
  name: string
  /** i18n 键：kb.chain.<id>.desc */
  desc: string
  codePath: string
}

